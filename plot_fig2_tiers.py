#!/usr/bin/env python3
"""Fig. 2b -- data lifetime vs reads per write, for the two memory tiers.

Plot code lives here; the DATA lives in the analysis repo (sibling folder
H_RAG_cuad_v3.0_MMR_deviceModeling), where it is regenerated by
    python scripts/make_fig2_counts.py --out figures/fig2

Reads   <analysis repo>/figures/fig2/fig2_tiers.csv
Writes  ./figures/fig2b.{png,pdf,svg}

    python plot_fig2_tiers.py
    python plot_fig2_tiers.py --data /some/other/fig2 --outdir figures
    HAIMDC_ROOT=D:/codes/H_RAG_... python plot_fig2_tiers.py
"""
from __future__ import annotations

import argparse
import csv
import math
import os
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle

# --------------------------------------------------------------------- paths --
PLOT_ROOT = Path(__file__).resolve().parent
ANALYSIS_ROOT = Path(os.environ.get("HAIMDC_ROOT",
                                    PLOT_ROOT.parent / "H_RAG_cuad_v3.0_MMR_deviceModeling"))
DEFAULT_DATA = ANALYSIS_ROOT / "figures" / "fig2"
OUTDIR = PLOT_ROOT / "figures"

# ---------------------------------------------------------------------- style --
STATIC = "#4A6FA5"      # muted blue
DYNAMIC = "#C1666B"     # muted red
BOX_ALPHA = 0.14
PAD = 1.15              # fractional padding around each tier box


def box(ax, xs, ys, color, label):
    x0, x1 = min(xs) / PAD, max(xs) * PAD
    y0, y1 = min(ys) / PAD, max(ys) * PAD
    ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, facecolor=color,
                           alpha=BOX_ALPHA, edgecolor=color, linewidth=1.4, zorder=1))
    ax.scatter(xs, ys, s=34, color=color, zorder=3, label=label,
               edgecolor="white", linewidth=0.7)
    return x0, x1, y0, y1


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA,
                    help=f"directory holding fig2_tiers.csv (default: {DEFAULT_DATA})")
    ap.add_argument("--outdir", type=Path, default=OUTDIR)
    ap.add_argument("--name", default="fig2b")
    a = ap.parse_args()

    csv_path = a.data / "fig2_tiers.csv"
    if not csv_path.is_file():
        raise SystemExit(
            f"data not found: {csv_path}\n"
            f"Expected the analysis repo at {ANALYSIS_ROOT} (set HAIMDC_ROOT or pass --data).\n"
            f"Regenerate it there with: python scripts/make_fig2_counts.py --out figures/fig2")

    rows = list(csv.DictReader(open(csv_path, encoding="utf-8")))
    sta = [r for r in rows if r["tier"].startswith("static")]
    dyn = [r for r in rows if r["tier"].startswith("dynamic")]
    if not sta or not dyn:
        raise SystemExit(f"{csv_path} is missing one of the two tiers")

    fig, ax = plt.subplots(figsize=(5.6, 4.2), dpi=200)
    ax.set_xscale("log"); ax.set_yscale("log")

    bs = box(ax, [float(r["lifetime_queries"]) for r in sta],
                 [float(r["reads_per_write"]) for r in sta],
             STATIC, "static tier (centroids)")
    bd = box(ax, [float(r["lifetime_queries"]) for r in dyn],
                 [float(r["reads_per_write"]) for r in dyn],
             DYNAMIC, "dynamic tier (selected set S)")

    for r in sta:
        ax.annotate(r["scenario"].split("_", 1)[0],
                    (float(r["lifetime_queries"]), float(r["reads_per_write"])),
                    textcoords="offset points", xytext=(6, -9), fontsize=6.5, color=STATIC)
    for i, r in enumerate(sorted(dyn, key=lambda z: float(z["reads_per_write"]))):
        ax.annotate(f"{r['scope']} k={r['k']}",
                    (float(r["lifetime_queries"]), float(r["reads_per_write"])),
                    textcoords="offset points", xytext=(8, (-4, 5, -11, 12)[i % 4]),
                    fontsize=6.5, color=DYNAMIC)

    # lifetime gap: the full min-max range across the Q_rebuild scenarios,
    # not the distance between the two drawn box edges.
    gap_lo, gap_hi = bd[1], bs[0]
    if gap_hi > gap_lo:
        ymid = (bd[2] * bs[3]) ** 0.5
        ax.annotate("", xy=(gap_hi, ymid), xytext=(gap_lo, ymid),
                    arrowprops=dict(arrowstyle="<->", color="0.45", lw=1.0))
        lifes = [float(r["lifetime_queries"]) for r in dyn]
        qs = [float(r["lifetime_queries"]) for r in sta]
        gaps = [math.log10(q / l) for q in qs for l in lifes]
        ax.text((gap_lo * gap_hi) ** 0.5, ymid * 1.3,
                f"lifetime gap\n{min(gaps):.1f}-{max(gaps):.1f} decades",
                ha="center", va="bottom", fontsize=7, color="0.35", linespacing=1.3)

    ax.set_xlabel("data lifetime (queries)")
    ax.set_ylabel("reads per write")
    ax.grid(True, which="major", linestyle=":", linewidth=0.5, color="0.8")
    ax.legend(frameon=False, fontsize=7.5, loc="lower right")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()

    a.outdir.mkdir(parents=True, exist_ok=True)
    for ext in ("png", "pdf", "svg"):
        p = a.outdir / f"{a.name}.{ext}"
        fig.savefig(p)
        print("wrote", p)


if __name__ == "__main__":
    main()
