#!/usr/bin/env python3
"""Fig. 2 -- stored-value precision requirement per memory tier.

Plot code lives here; the DATA lives in the analysis repo (sibling folder
H_RAG_cuad_v3.0_MMR_deviceModeling), where it is regenerated by
    python scripts/make_fig2_precision.py --out figures/fig2

x = per-cell stored-value write resolution sigma; the top axis is the equivalent
storage resolution in bits, log2(FS / 6 sigma), using each tier's own full
scale. y is each metric relative to its sigma = 0 value, so both tiers share one
scale; the dashed line is the -1 % criterion whose crossings are tabulated in
fig2_precision_bits.csv.

Style -- fonts, bold ticks, grid, spines, the locked-file-safe writer -- is
imported from ``read_disturb_plots`` rather than restated, so this figure and
the read-disturb set cannot drift apart.

Reads   <analysis repo>/figures/fig2/fig2_precision.csv
        <analysis repo>/figures/fig2/fig2_precision_meta.json

The dynamic tier's full scale was corrected from 6 V to 3 V (the stored-value
window of a 4T2C node, +-1.5 V; the +-3 V figure is the SL drive swing). This
did NOT move the bit axis. In make_fig2_precision.py the same FS_DYNAMIC both
converts a write resolution in mV into embedding units and divides the bit
conversion, so it cancels: bit = log2(x_span / 6*noise_emb). What the
correction changes is the volt label on sigma, which halves. Correcting only
the bit conversion, and leaving the noise injection on the 6 V reference,
would have shifted every dynamic bit down by exactly 1 -- spuriously.
Writes  ./figures/fig2_precision.png           both tiers side by side
        ./figures/fig2_precision_static.png    static tier alone
        ./figures/fig2_precision_dynamic.png   dynamic tier alone

    python plot_fig2_precision.py
    python plot_fig2_precision.py --data /some/other/fig2 --ymin 0.7
    python plot_fig2_precision.py --only static
    HAIMDC_ROOT=D:/codes/H_RAG_... python plot_fig2_precision.py
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import os
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

# Shared figure style, one source of truth with the read-disturb figures.
from read_disturb_plots import (      # noqa: E402
    LABEL_BBOX, TICK_SIZE,
    _apply_style, _bold_ticks, _hide_top_right, _savefig,
)

# --------------------------------------------------------------------- paths --
PLOT_ROOT = Path(__file__).resolve().parent
ANALYSIS_ROOT = Path(os.environ.get("HAIMDC_ROOT",
                                    PLOT_ROOT.parent / "H_RAG_cuad_v3.0_MMR_deviceModeling"))
DEFAULT_DATA = ANALYSIS_ROOT / "figures" / "fig2"
OUTDIR = PLOT_ROOT / "figures"

# ---------------------------------------------------------------------- style --
# (csv column, colour, legend label) -- drop a row to remove a curve
SERIES = [("mmr_recall",           "#4A6FA5", "MMR recall@5"),
          ("mmr_ndcg",             "#3F7D5A", "MMR nDCG@5"),
          ("top5_jaccard",         "#C1666B", "top-5 set Jaccard vs ideal"),
          ("centroid_kendall_tau", "#B08447", "rank Kendall tau")]

# The Kendall tau column holds a different ordering in each tier -- centroids
# on the static side, the 50 candidates by redundancy against the ideal
# selected set on the dynamic side -- so the legend has to say which. The
# shared SERIES label stays generic and the tier supplies the rest.
TAU_LABEL = {"static": "centroid rank Kendall tau",
             "dynamic": "candidate rank Kendall tau"}

# Series a tier computes but does not draw. The dynamic tau stays in
# fig2_precision.csv and keeps its crossing row in fig2_precision_bits.csv --
# report_bits() still prints it, and it is still the tier's strictest bound --
# it is only kept out of the panel. Its label in TAU_LABEL is left in place so
# putting the curve back is a matter of emptying this set.
SKIP_SERIES = {"dynamic": {"centroid_kendall_tau"}}

# Measured device resolutions, drawn as reference lines only (mV). Keyed by the
# cell they came from so the provenance stays in the code, but only the value is
# printed -- a cell id means nothing to a reader of the figure.
# Emptied: the reference lines are no longer drawn. The measured values are
# kept here as a record -- R1C1 5.6 mV, R0C0 18.4 mV on the static tier -- so
# putting a line back is a matter of restoring an entry.
MEASURED = {"static": {},
            "dynamic": {}}

PANELS = [("static",  "static tier (centroids)"),
          ("dynamic", "dynamic tier (selected set S)")]

DROP_LINE = 0.99        # the -1 % criterion
BIT_TICKS = range(-2, 13)

# Both tiers start their x axis at the same storage resolution, so the two
# panels can be read against each other in bits even though their full scales
# (and therefore their sigma in mV) differ by 4.6x.
START_BIT = 7
# ...and both stop at the same one. The right edge was data-driven (the largest
# sigma swept), which let the panels run out to about -1 bit -- past the point
# where the bit count still means anything, since 6 sigma there exceeds full
# scale. Ending at 1 bit keeps the axis over the range the requirement is
# actually read off. The curves still carry on beyond it; they are clipped, not
# dropped, and the crossings printed by report_bits() are unaffected.
END_BIT = 1
# sigma = 0 cannot sit on a log axis. It is drawn in the margin left of the
# first bit tick, which is what it is: finer than the axis resolves. The axis
# starts far enough left to keep it visible -- on the dynamic tier its old
# placement (half the smallest sigma) fell inside the 9-bit position and the
# normalisation anchor would have been clipped away.
SIGMA0_GAP = 1.30       # sigma = 0 sits at x(START_BIT) / SIGMA0_GAP
XLIM_PAD_LO = 1.65      # left edge at x(START_BIT) / XLIM_PAD_LO
XLIM_PAD_HI = 1.18      # right edge at x(END_BIT) * XLIM_PAD_HI

# Panel sizes. The axes itself is square (set_box_aspect below); these are the
# sizes of the whole figure, which also has to hold the axis labels, the titles
# and the legend strip underneath. The heights are chosen so that the square
# axes is what fills the width -- too short and constrained layout shrinks the
# axes to keep the aspect, leaving white bars down either side.
SIZE_PAIR = (6.4, 4.3)
# The single-tier figures cannot share one height: the legend is one column, and
# the static tier has four entries to the dynamic tier's three, so a height that
# fits one clips the other's title or leaves the other a white band. The height
# is built from the panel plus however many legend rows the tier actually has.
SIZE_ONE_W = 3.3
SIZE_ONE_H0 = 3.35      # title + square panel + x label
SIZE_ONE_H_ROW = 0.28   # per legend row, at FONT_LEGEND with labelspacing 0.35

# A square panel, not the wide one the sweep's 2-decade x range would give.
# Both tiers span the same 7 -> 1 bit, so a fixed aspect makes the two panels
# literally the same shape and the curves directly comparable by eye.
BOX_ASPECT = 1.0

Y_LABEL = "metric / value at $\\sigma$ = 0"

# Font overrides for this figure only. _apply_style() brings the read-disturb
# sizes; these raise the axis labels and the legend on top of them, so the
# read-disturb figures are not dragged along. Tick sizes stay shared.
FONT_AXIS_LABEL = 11        # 9 in the shared style
FONT_LEGEND = 10            # 8 in the shared style
AXIS_LABEL_WEIGHT = "bold"


def load(data_dir: Path) -> tuple[list[dict], dict]:
    csv_path = data_dir / "fig2_precision.csv"
    meta_path = data_dir / "fig2_precision_meta.json"
    if not csv_path.is_file():
        raise SystemExit(
            f"data not found: {csv_path}\n"
            f"Expected the analysis repo at {ANALYSIS_ROOT} (set HAIMDC_ROOT or pass --data).\n"
            f"Regenerate it there with: python scripts/make_fig2_precision.py --out figures/fig2")
    rows = list(csv.DictReader(open(csv_path, encoding="utf-8")))
    meta = json.load(open(meta_path, encoding="utf-8"))
    return rows, meta


def fmt_bits(b: float) -> str:
    """Bit counts below 1 are reported as '< 1', never as a number.

    bit = log2(FS / 6 sigma) goes negative once 6 sigma exceeds full scale,
    and a negative bit count is not a resolution -- it is the statement that
    the tier survives a write step coarser than the whole stored range, i.e.
    that it imposes no resolution requirement at all. Printing '-0.99 bit'
    invites it to be read as a requirement with a sign error.
    """
    return "< 1" if b < 1.0 else f"{b:.2f}"


def report_bits(data_dir: Path, regime_of: dict[str, str]) -> None:
    """Print the crossing table for the caption, with the < 1 rule applied."""
    path = data_dir / "fig2_precision_bits.csv"
    if not path.exists():
        print(f"(no {path.name}; skipping the bit table)")
        return
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    print("crossing table (bit = log2[FS / 6 sigma]):")
    for tier, _ in PANELS:
        for r in rows:
            if r["tier"] != tier or r["regime"] != regime_of[tier]:
                continue
            if not r["bits_6sigma"]:
                continue
            print(f"  {tier:8s} {r['metric']:20s} sigma* = "
                  f"{float(r['sigma_star_mv']):8.2f} mV   "
                  f"{fmt_bits(float(r['bits_6sigma'])):>5s} bit")


def draw_panel(ax: plt.Axes, rows: list[dict], tier: str, title: str,
               fs: float, *, regime: str, ymin: float,
               with_ylabel: bool) -> tuple[list, list[str]]:
    """One tier on one axes; returns the legend handles for the caller.

    The legend goes below the figure rather than inside the axes: the only
    clear space in the panel is the lower left, and that is exactly where the
    measured-resolution reference lines are labelled.
    """
    grp = collections.defaultdict(list)
    for r in rows:
        if r["tier"] == tier and r["regime"] == regime:
            grp[float(r["sigma_mv"])].append(r)
    if not grp:
        raise SystemExit(f"no rows for tier={tier} regime={regime}")
    xs = sorted(grp)
    x9 = 1000 * fs / (6 * 2.0 ** START_BIT)      # sigma at START_BIT, in mV
    x_end = 1000 * fs / (6 * 2.0 ** END_BIT)     # sigma at END_BIT, in mV
    xm = np.array([x9 / SIGMA0_GAP if x == 0 else x for x in xs])

    for key, col, lab in SERIES:
        if key in SKIP_SERIES.get(tier, ()):
            continue
        m, s = [], []
        for x in xs:
            v = [float(r[key]) for r in grp[x] if r.get(key, "") != ""]
            m.append(np.mean(v) if v else np.nan)
            s.append(np.std(v) if len(v) > 1 else 0.0)
        m, s = np.array(m), np.array(s)
        if np.isnan(m).all() or not m[0]:
            continue                      # metric absent for this tier
        if key == "centroid_kendall_tau":
            lab = TAU_LABEL.get(tier, lab)
        ax.plot(xm, m / m[0], "-o", color=col, ms=3.2, lw=1.3, label=lab)
        ax.fill_between(xm, (m - s) / m[0], (m + s) / m[0], color=col,
                        alpha=0.13, lw=0)

    ax.axhline(DROP_LINE, color="0.45", lw=0.9, ls="--")
    ax.set_xscale("log")
    ax.set_xlim(x9 / XLIM_PAD_LO, x_end * XLIM_PAD_HI)
    ax.set_ylim(ymin, 1.03)
    # The -1 % criterion is drawn but not labelled, like the measured-resolution
    # lines: the panel has no clear space for it. Both dashed and dotted lines
    # have to be named in the caption.
    # The measured resolutions are marked but not labelled: naming them in the
    # panel crowded the only clear space it has. What the dotted lines are has
    # to be said in the caption -- MEASURED still holds the values, and the
    # console prints them on every run.
    for _cell, sg in MEASURED[tier].items():
        ax.axvline(sg, color="0.6", lw=0.8, ls=":")

    # The bit number is the only x axis. sigma in mV differs between the tiers
    # -- their full scales differ by 2.3x (1.3106 V vs 3 V) -- and is what made the two panels
    # look incomparable, while the bit count is the quantity the requirement is
    # stated in. Ticks run high to low left to right: sigma grows rightwards,
    # so resolution falls.
    lo, hi = ax.get_xlim()
    keep = [(1000 * fs / (6 * 2.0 ** b), b) for b in BIT_TICKS]
    keep = [(pos, b) for pos, b in keep if lo < pos < hi]
    ax.set_xticks([pos for pos, _ in keep])
    ax.set_xticklabels([str(b) for _, b in keep])
    ax.minorticks_off()
    ax.set_box_aspect(BOX_ASPECT)
    ax.set_xlabel("storage resolution (bit = $\\log_2$[FS / 6$\\sigma$])")
    ax.set_title(title)
    if with_ylabel:
        ax.set_ylabel(Y_LABEL)
    _hide_top_right(ax)
    return ax.get_legend_handles_labels()


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA,
                    help=f"directory holding fig2_precision.csv (default: {DEFAULT_DATA})")
    ap.add_argument("--outdir", type=Path, default=OUTDIR)
    ap.add_argument("--name", default="fig2_precision")
    ap.add_argument("--regime", default="exact", choices=["exact", "pq"],
                    help="in-pool re-rank regime (the static tier has both)")
    ap.add_argument("--ymin", type=float, default=0.5)
    ap.add_argument("--only", choices=[t for t, _ in PANELS],
                    help="write just this tier's own figure")
    ap.add_argument("--no-pair", action="store_true",
                    help="skip the two-panel figure")
    a = ap.parse_args()

    rows, meta = load(a.data)
    print(f"dashed line: the {100 * (1 - DROP_LINE):.0f} % drop criterion "
          f"(y = {DROP_LINE:g}), drawn unlabelled")
    for tier, marks in MEASURED.items():
        if marks:
            print(f"{tier} tier, dotted reference lines: "
                  + ", ".join(f"{cell} {sg} mV" for cell, sg in marks.items())
                  + "  (drawn unlabelled; state them in the caption)")
    FS = {"static": meta["full_scale_static_v"],
          "dynamic": meta["full_scale_dynamic_v"]}
    print("full scale behind the bit axis: "
          + ", ".join(f"{t} {FS[t]:g} V" for t, _ in PANELS)
          + "  (bit = log2[FS / 6 sigma]; no longer shown in the figure)")
    # the dynamic tier is only swept in the 'exact' regime
    regime_of = {"static": a.regime, "dynamic": "exact"}
    report_bits(a.data, regime_of)

    _apply_style()
    plt.rcParams.update({
        "axes.labelsize": FONT_AXIS_LABEL,
        "axes.labelweight": AXIS_LABEL_WEIGHT,
        "legend.fontsize": FONT_LEGEND,
    })
    a.outdir.mkdir(parents=True, exist_ok=True)
    panels = [(t, n) for t, n in PANELS if a.only is None or t == a.only]

    # -- one figure per tier ------------------------------------------------
    for tier, title in panels:
        fig, ax = plt.subplots(figsize=(SIZE_ONE_W, SIZE_ONE_H0))
        handles, labels = draw_panel(
            ax, rows, tier, title, FS[tier], regime=regime_of[tier],
            ymin=a.ymin, with_ylabel=True)
        # One column: at FONT_LEGEND and this width two columns run off the
        # edge, and clipping the key is worse than a taller legend.
        fig.legend(handles, labels, loc="outside lower center", ncol=1,
                   frameon=False, handlelength=1.6, labelspacing=0.35)
        # Now that the entries are known, give the figure the height they need.
        # Resizing after the legend exists is what keeps the panel square
        # without the tier's entry count leaking into a hand-tuned constant.
        fig.set_size_inches(SIZE_ONE_W,
                            SIZE_ONE_H0 + SIZE_ONE_H_ROW * len(labels))
        _savefig(fig, a.outdir / f"{a.name}_{tier}.png")
        print("wrote", a.outdir / f"{a.name}_{tier}.png")
        plt.close(fig)

    # -- and the pair, kept so the old filename still resolves --------------
    if a.no_pair or a.only is not None:
        return
    fig, axes = plt.subplots(1, 2, figsize=SIZE_PAIR)
    handles: list = []
    labels: list[str] = []
    for ax, (tier, title) in zip(axes, PANELS):
        h, l = draw_panel(ax, rows, tier, title, FS[tier],
                          regime=regime_of[tier], ymin=a.ymin,
                          with_ylabel=ax is axes[0])
        if len(h) > len(handles):      # the static tier carries every metric
            handles, labels = h, l
    fig.legend(handles, labels, loc="outside lower center", ncol=2,
               frameon=False, handlelength=1.6, columnspacing=1.6,
               labelspacing=0.35)
    _savefig(fig, a.outdir / f"{a.name}.png")
    print("wrote", a.outdir / f"{a.name}.png")
    plt.close(fig)


if __name__ == "__main__":
    main()
